import UIKit

extension UIColor {
    
    class var cellBackgroundColor:UIColor {
        return UIColor(red: 0.72, green: 0.85, blue: 0.78, alpha: 1.0)
    }
    
    class var navBarColor:UIColor {
        return UIColor(red: 0.02, green: 0.06, blue: 0.26, alpha: 1.0)
    }
    
    class var firstGradientColor:UIColor {
        return UIColor(red: 0.72, green: 0.85, blue: 0.78, alpha: 1.0)
    }
    class var secondGradientColor:UIColor {
        return UIColor(red: 0.48, green: 0.79, blue: 0.81, alpha: 1.0)
    }
    class var darkBlue:UIColor {
        return UIColor(red: 0.02, green: 0.06, blue: 0.26, alpha: 1.0)
    }
}
